import React, { useState, useEffect } from 'react';
import { Card, CardContent } from '../components/ui/Card';
import { Badge } from '../components/ui/Badge';
import { Clock, AlertTriangle } from 'lucide-react';
import { FranchiseOpsLogo } from '../components/brand/FranchiseOpsLogo';
import { getInsights, getAgentRuns } from '../services/dataService';
import { AIInsight, AgentRun } from '../types';

export function AIInsights() {
  const [insights, setInsights] = useState<AIInsight[]>([]);
  const [runs, setRuns] = useState<AgentRun[]>([]);

  useEffect(() => {
    getInsights().then(setInsights);
    getAgentRuns().then(setRuns);
  }, []);

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl font-bold text-slate-900 tracking-tight">Franchise Intelligence</h1>
        <p className="text-slate-500 mt-1">Cross-domain analysis and operational insights generated by AI agents.</p>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        <div className="lg:col-span-2 space-y-6">
          {insights.map(insight => (
            <Card key={insight.id} className="border-l-4 border-l-indigo-600">
              <CardContent className="p-6">
                <div className="flex justify-between items-start mb-4">
                  <div className="flex items-center gap-2">
                    <FranchiseOpsLogo className="w-5 h-5" />
                    <span className="text-sm font-semibold text-indigo-600 uppercase tracking-wider">{insight.related_agent}</span>
                  </div>
                  <Badge variant={insight.priority === 'Critical' ? 'danger' : 'warning'}>{insight.priority}</Badge>
                </div>
                
                <h3 className="text-xl font-bold text-slate-900 mb-2">{insight.title}</h3>
                <p className="text-slate-700 font-medium mb-6">{insight.finding}</p>
                
                <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                  <div className="bg-slate-50 p-4 rounded-lg border border-slate-100">
                    <h4 className="text-sm font-semibold text-slate-900 mb-2 flex items-center"><AlertTriangle className="w-4 h-4 mr-1 text-amber-500"/> Why is this happening?</h4>
                    <ul className="list-disc list-inside text-sm text-slate-600 space-y-1">
                      {insight.possible_causes.map((c, i) => <li key={i}>{c}</li>)}
                    </ul>
                  </div>
                  <div className="bg-emerald-50 p-4 rounded-lg border border-emerald-100">
                    <h4 className="text-sm font-semibold text-emerald-900 mb-2">Recommendation</h4>
                    <p className="text-sm text-emerald-800">{insight.recommendation}</p>
                  </div>
                </div>
              </CardContent>
            </Card>
          ))}
        </div>
        
        <div className="space-y-6">
          <Card>
            <div className="px-6 py-4 border-b border-slate-100 flex items-center justify-between">
              <h3 className="font-semibold text-slate-900">Recent Agent Runs</h3>
              <Clock className="w-4 h-4 text-slate-400" />
            </div>
            <div className="p-0">
              <ul className="divide-y divide-slate-100">
                {runs.map(run => (
                  <li key={run.id} className="p-4 hover:bg-slate-50">
                    <div className="flex justify-between items-start mb-1">
                      <span className="text-sm font-medium text-slate-900">{run.agent}</span>
                      <Badge variant={run.status === 'Completed' ? 'success' : run.status === 'Running' ? 'info' : 'default'} className="text-[10px]">
                        {run.status}
                      </Badge>
                    </div>
                    <p className="text-xs text-slate-500 mb-2">Task: {run.task}</p>
                    {run.output && <p className="text-xs text-slate-700 bg-white p-2 rounded border border-slate-200 font-mono">{run.output}</p>}
                  </li>
                ))}
              </ul>
            </div>
          </Card>
        </div>
      </div>
    </div>
  );
}
